"""Generate winget/configuration.winget (owner mode) and winget/configuration.edge.winget (edge mode).

Both are WinGet Configuration files (DSC schema 0.2), applied with
`winget configure --file winget\\configuration.winget --accept-configuration-agreements`.
Packages whose installers write machine-wide (MSI into Program Files, Windows services) ask for an elevated context;
winget then shows one UAC prompt for all of them.
"""
from __future__ import annotations

from pathlib import Path

import yaml

from . import REPO, catalog, info

WINGET_DIR = REPO / "winget"


def _packages(key: str) -> list[tuple[str, str, str, bool]]:
    """(resource id, winget package id, description, needs elevation) from config/installer.yaml winget.<key>. Keep
    in step with docs/plans/INSTALL.md section 2.1."""
    return [(str(p["id"]), str(p["package"]), str(p["description"]), bool(p.get("elevated")))
            for p in (catalog.section("winget").get(key) or ())]


OWNER_PACKAGES = _packages("packages")
EDGE_PACKAGES = _packages("edge_packages")


def package_id(rid: str) -> str:
    """The winget id of one of the packages above ("git" -> "Git.Git"), for messages that say what to install."""
    return next((pkg for r, pkg, _d, _e in OWNER_PACKAGES + EDGE_PACKAGES if r == rid), rid)


HEADER = (
    "# yaml-language-server: $schema=https://aka.ms/configuration-dsc-schema/0.2\n"
    "# GENERATED by `uv run scripts/stack.py build` from config/installer.yaml (winget). Edit that list, not this file.\n"
    "# Apply: winget configure --file winget\\{name} --accept-configuration-agreements\n"
    "# Not covered here: the NVIDIA driver, Python (fetched by uv), uv tools and Keycloak (stack.py setup).\n"
)


def build_config(packages: list[tuple[str, str, str, bool]]) -> str:
    resources = []
    for rid, pkg, desc, elevated in packages:
        directives = {"description": desc, "allowPrerelease": False}
        if elevated:
            directives["securityContext"] = "elevated"
        resources.append(
            {
                "resource": "Microsoft.WinGet.DSC/WinGetPackage",
                "id": rid,
                "directives": directives,
                "settings": {"id": pkg, "source": "winget"},
            }
        )
    doc = {"properties": {"configurationVersion": "0.2.0", "resources": resources}}
    return yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=120)


def build() -> list[Path]:
    WINGET_DIR.mkdir(parents=True, exist_ok=True)
    out = []
    for name, packages in (("configuration.winget", OWNER_PACKAGES), ("configuration.edge.winget", OWNER_PACKAGES + EDGE_PACKAGES)):
        path = WINGET_DIR / name
        path.write_text(HEADER.format(name=name) + build_config(packages), encoding="utf-8", newline="\n")
        out.append(path)
    info(f"winget: wrote {', '.join(str(p.relative_to(REPO)) for p in out)}")
    return out
